export type CategoryId = 'plantillas' | 'presets' | 'iconos' | 'fuentes' | 'modelos-3d' | 'plugins' | 'cursos' | 'packs' | 'android'

export interface Product {
  id: string
  slug: string
  name: string
  brand: string
  category: CategoryId
  price: number
  oldPrice?: number
  rating: number
  reviews: number
  stock: number
  badge?: 'nuevo' | 'popular' | 'top'
  description: string
  features: string[]
  /** Formato del archivo descargable (ZIP, FIG, PSD, PDF, MP4, OTF, ...). */
  fileType: string
  /** Tamaño aproximado del archivo (ej. "24 MB"). */
  fileSize: string
  /** Compatibilidad (ej. "Windows · macOS · Linux"). */
  compatibility: string
  /** Tipo de licencia (ej. "Uso personal y comercial"). */
  license: string
  /** Nº de descargas realizadas. */
  downloads: number
  /** Versión actual del archivo digital (ej. "1.2.0"). */
  version?: string
  /** Qué incluye la descarga. */
  includes: string[]
  /** Requisitos del sistema / software necesario. */
  requirements: string[]
  /** Política de actualizaciones. */
  updates: string
  /** Soporte incluido. */
  support: string
  shipDays?: number
  colors?: string[]
  image: string
  images: string[]
  createdAt: string
  /** Vendedor (solo productos publicados por usuarios; los de la tienda no lo tienen). */
  owner?: { id: number; name: string; verified?: boolean } | null
  /** Código de producto (para todos los productos, incluidos los de la tienda). */
  productCode?: string | null
  /** Estado de visibilidad (productos con ubicación real en la tienda). */
  status?: 'active' | 'hidden'
  /** Garantía indicada por el vendedor (ej. "12 meses"). */
  warranty?: string
}

