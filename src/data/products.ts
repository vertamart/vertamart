export type CategoryId = 'audio' | 'wearables' | 'teclado' | 'mouse' | 'carga' | 'monitor'

export interface Product {
  id: string
  slug: string
  name: string
  brand: string
  category: CategoryId
  price: number
  oldPrice?: number
  rating: number
  reviews: number
  stock: number
  badge?: 'nuevo' | 'popular' | 'top'
  description: string
  features: string[]
  shipDays: number
  colors: string[]
  image: string
  images: string[]
  createdAt: string
  /** Vendedor (solo productos publicados por usuarios; los de la tienda no lo tienen). */
  owner?: { id: number; name: string; verified?: boolean } | null
  /** Código de producto (para todos los productos, incluidos los de la tienda). */
  productCode?: string | null
  /** Estado de visibilidad (productos con ubicación real en la tienda). */
  status?: 'active' | 'hidden'
  /** Garantía indicada por el vendedor (ej. "12 meses"). */
  warranty?: string
}

export interface Category {
  id: CategoryId
  name: string
  tagline: string
}

