/**
 * Sistema de idiomas (i18n) ES / EN.
 *
 * El idioma se detecta automáticamente del dispositivo (navigator.language)
 * la primera vez y se guarda en localStorage. `t(key, vars)` devuelve la
 * traducción; las claves que falten en un idioma vuelven al texto original.
 */

